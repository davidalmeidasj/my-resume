const BAYER = [
  [0, 8, 2, 10],
  [12, 4, 14, 6],
  [3, 11, 1, 9],
  [15, 7, 13, 5],
]

export const ditherFrame = (x: number, y: number) => BAYER[y % 4]![x % 4]!

export type BitmapCell = { x: number; y: number; frame: number }

export type BitmapGlyph = { char: string; x: number; cells: BitmapCell[] }

export const glyphCells = (char: string, offsetX = 0): BitmapCell[] =>
  (GLYPHS[char] ?? []).flatMap((row, y) =>
    [...row].flatMap((bit, x) =>
      bit === '1' ? [{ x: offsetX + x, y, frame: ditherFrame(offsetX + x, y) }] : [],
    ),
  )

export const layoutLine = (text: string) => {
  const glyphs: BitmapGlyph[] = []
  let x = 0
  for (const char of text.toUpperCase()) {
    if (GLYPHS[char]) {
      glyphs.push({ char, x, cells: glyphCells(char, x) })
      x += GLYPH_COLS + 1
    } else {
      x += 3
    }
  }
  return { glyphs, cols: Math.max(0, x - 1) }
}
